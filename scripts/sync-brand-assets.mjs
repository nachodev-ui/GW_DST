import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'artifacts/gasway-brand-v1');
const mobile = path.join(root, 'apps/mobile');
const geometry = JSON.parse(await readFile(path.join(source, 'masters/geometry.json'), 'utf8'));
const destination = path.join(mobile, 'assets/identity');
const assets = {
  'icon.png': 'png/icon/app-icon-lime-on-dark-1024.png',
  'adaptive-foreground.png': 'png/android/adaptive-foreground-lime-1024.png',
  'adaptive-monochrome.png': 'png/android/adaptive-foreground-monochrome-1024.png',
  'splash-light.png': 'png/splash/splash-monogram-light-1024.png',
  'splash-dark.png': 'png/splash/splash-monogram-dark-1024.png',
  'favicon.png': 'png/favicon/favicon-lime-on-dark-48.png',
};
await mkdir(destination, { recursive: true });
const records = [];
for (const [name, original] of Object.entries(assets)) {
  const buffer = await readFile(path.join(source, original));
  await copyFile(path.join(source, original), path.join(destination, name));
  records.push({
    file: name,
    source: original,
    sha256: createHash('sha256').update(buffer).digest('hex'),
  });
}
const config = await resolveConfig(path.join(root, 'package.json'));
async function generated(relative, name, value) {
  const target = path.join(mobile, relative);
  await mkdir(path.dirname(target), { recursive: true });
  const code = `// Generated by npm run brand:sync from artifacts/gasway-brand-v1.\n// Edit the package masters or sync script, then regenerate.\nexport const ${name} = ${JSON.stringify(value, null, 2)} as const;\n`;
  await writeFile(target, await format(code, { ...config, parser: 'typescript' }), 'utf8');
}
const brand = {
  colors: geometry.palette,
  logo: { wordmarkWidth: 160, monogramWidth: 32 },
  splash: { imageWidth: 240 },
  assets: Object.fromEntries(
    Object.keys(assets).map((name) => [
      name.replace(/\.png$/, '').replace(/-([a-z])/g, (_, letter) => letter.toUpperCase()),
      `./assets/identity/${name}`,
    ]),
  ),
};
await generated('src/theme/brand.ts', 'brand', brand);
// Expo evaluates app.config.ts in Node without resolving sibling TypeScript imports.
await writeFile(
  path.join(destination, 'brand.json'),
  await format(JSON.stringify(brand), {
    ...config,
    parser: 'json',
  }),
  'utf8',
);
await generated('src/shared/branding/gasway-geometry.ts', 'gaswayGeometry', {
  wordmark: geometry.wordmark,
  monogram: geometry.monogram,
  dot: geometry.dot,
  glyphs: geometry.glyphs,
  placements: geometry.placements,
});
await writeFile(
  path.join(destination, 'manifest.json'),
  await format(
    JSON.stringify({
      source: 'artifacts/gasway-brand-v1',
      version: geometry.version,
      files: records,
    }),
    { ...config, parser: 'json' },
  ),
  'utf8',
);
console.log(`Gasway: ${records.length} assets and shared vector/theme sources synchronized.`);
